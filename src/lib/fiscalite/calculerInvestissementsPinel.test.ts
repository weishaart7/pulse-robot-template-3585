  it('plafond commun de 300 000 €, taux annuel décroissant', () => {
    expect(p({ case7nm: 200000, case7qm: 200000 }).reductions).toBe(6000);
    expect(p({ case7nm: 400000, case7sd: 400000 }).reductions).toBe(6000);
    expect(p({ case7lu: 200000, case7lw: 200000 }).reductions).toBe(9667);
  });
  it('compléments : plafond par case', () => {
    expect(p({ case7xa: 200000, case7rx: 200000 }).reductions).toBe(6000);
  });
  it('reports plafonnés ou non', () => {
    expect(p({ case7jb: 7000 }).reductions).toBe(6000);
    expect(p({ case7mm: 17000 }).reductions).toBe(9667);
    expect(p({ case7rb: 9000 }).reductions).toBe(9000);
    expect(p({ case7rd: 17000 }).reductions).toBe(17000);
    expect(p({ case7jm: 5000, case7lm: 5000 }).reductions).toBe(0);
  });
  it('plafonnement global : métropole 10 000 €, outre-mer dans la majoration de 8 000 €', () => {
    const metro = p({ case7rb: 50000 });
    expect(calculerPlafonnementNiches({ courants: metro.avantagesPlafonnesCourants, esus: 0, outreMer: metro.outreMer }).excedent).toBe(40000);
    const om = p({ case7lw: 400000 });
    // + crédit 7DB de 10 000 € → baisse totale de 18 000 € (simulateur).
    expect(calculerPlafonnementNiches({ courants: 10000, esus: 0, outreMer: om.outreMer }).excedent).toBe(3500);
    expect(calculerPlafonnementNiches({ courants: 10000, esus: 0, outreMer: om.outreMer + 8000 }).excedent).toBe(11500);
  });
