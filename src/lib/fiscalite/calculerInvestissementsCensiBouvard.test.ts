/** Baisses d'impôt relevées sur le simulateur officiel 2026 (couple, RNI 470 890 €). */
const RNI = 470890;
const baisse = (o: Partial<ReductionsCreditsImpotInput>, credit = 0) => {
  const input = o as ReductionsCreditsImpotInput;
  const c = calculerInvestissementsCensiBouvard(input);
  const s = calculerInvestissementsScellier(input);
  const p = calculerInvestissementsPinel(input);
  const millesimes = { ...s.millesimes };
  for (const a of [2009, 2010, 2011, 2012] as const) millesimes[a] += c.millesimes[a];
  const courants = c.avantagesPlafonnesCourants + p.avantagesPlafonnesCourants + credit;
  const excedent = calculerPlafonnementNiches({ courants, esus: 0, outreMer: p.outreMer, millesimes, revenuNetImposable: RNI }).excedent;
  return c.reductions + s.reductions + p.reductions + credit - excedent;
};

